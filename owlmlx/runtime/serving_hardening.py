@dataclass(frozen=True, slots=True)
class UnifiedErrorEnvelope:
    """Outbound error response shape for the native namespace.

    Mirrors the OpenAI error-object shape closely enough that operator
    tooling can ingest it without translation, while adding the
    ``request_id`` field the wiring round populates from
    ``request.state.request_id``.

    ``http_status`` is carried alongside the body so that the wiring
    round's exception handler can return ``Response(content=...,
    status_code=envelope.http_status)`` without recomputing the code
    at the response site. This is the surface that closes the
    ``ok=False but HTTP 200`` mismatch the seven-line assessment
    flagged on Line 4.
    """

    id: str
    error_code: str
    message: str
    request_id: str | None
    http_status: int
    object: str = "error"

    def to_response_body(self) -> dict[str, Any]:
        return {
            "id": self.id,
            "object": self.object,
            "error_code": self.error_code,
            "message": self.message,
            "request_id": self.request_id,
            "http_status": self.http_status,
        }

    def to_json(self) -> str:
        return json.dumps(self.to_response_body(), separators=(",", ":"))


_RUNTIME_ERROR_CODE_TO_HTTP_STATUS: dict[str, int] = {
    "invalid_request": 400,
    "model_not_loaded": 409,
    "model_already_loaded": 409,
    "backend_error": 502,
    "memory_pressure": 503,
    "request_timeout": 504,
    "client_disconnected": 499,
}
"""Static, scaffold-grade mapping from runtime ``error_code`` strings to
HTTP status. The wiring round may extend or override this mapping at
install time; the scaffold only commits to defaults that match the
``runtime/types.py`` ``RuntimeErrorCode`` enum members observable in
``owlmlx`` today.
"""


_UNEXPECTED_ERROR_HTTP_STATUS = 500
"""HTTP status used for ``from_unexpected``. 500 because anything
that bypassed the runtime's typed error path is genuinely an internal
error from the caller's perspective.
"""


class ErrorEnvelopeBuilder:
    """Construct :class:`UnifiedErrorEnvelope` instances safely.

    The ``from_unexpected`` helper deliberately strips the raw
    exception's class name and message from any field that ships in
    the response body. The wiring round logs the underlying exception
    via the structured logger; the response only carries an opaque
    ``"unexpected_error"`` token. This is the no-leak contract the
    serving-surface architecture doc records.
    """

    def __init__(self, *, namespace: str = "owlmlx_native") -> None:
        self._namespace = namespace
        self._counter = 0

    def _next_envelope_id(self) -> str:
        self._counter += 1
        # Random suffix avoids collisions across worker restarts even
        # though there is currently only one worker per process.
        return f"err_{self._namespace}_{uuid.uuid4().hex[:16]}"

    def from_runtime_error_code(
        self,
        *,
        error_code: str,
        message: str,
        request_id: str | None,
        http_status: int | None = None,
    ) -> UnifiedErrorEnvelope:
        """Build an envelope from a typed runtime error.

        ``http_status`` is resolved from
        ``_RUNTIME_ERROR_CODE_TO_HTTP_STATUS`` when not supplied. An
        unknown ``error_code`` defaults to 500; the wiring round can
        narrow this when a domain-specific status fits better.
        """

        resolved_status = (
            http_status
            if http_status is not None
            else _RUNTIME_ERROR_CODE_TO_HTTP_STATUS.get(
                error_code, _UNEXPECTED_ERROR_HTTP_STATUS
            )
        )
        return UnifiedErrorEnvelope(
            id=self._next_envelope_id(),
            error_code=error_code,
            message=message,
            request_id=request_id,
            http_status=resolved_status,
        )

    def from_unexpected(
        self,
        exc: BaseException,
        *,
        request_id: str | None,
    ) -> UnifiedErrorEnvelope:
        """Build an envelope from an untyped exception WITHOUT leaking it.

        ``exc`` is accepted only so the wiring round can pass through
        whatever the framework caught; this method does NOT include the
        exception's class name, message, or traceback in the envelope.
        The wiring round is responsible for logging the exception
        itself elsewhere. The returned envelope's ``message`` is the
        constant ``"unexpected internal error"`` so probes cannot infer
        the exception class from response surface alone.
        """

        # Touch ``exc`` only to silence linters; we deliberately do not
        # read its attributes for the response body.
        _ = type(exc)
        return UnifiedErrorEnvelope(
            id=self._next_envelope_id(),
            error_code="unexpected_error",
            message="unexpected internal error",
            request_id=request_id,
            http_status=_UNEXPECTED_ERROR_HTTP_STATUS,
        )


