# ---------------------------------------------------------------------------
# 1. Request-id propagation
# ---------------------------------------------------------------------------


REQUEST_ID_HEADER = "x-request-id"
"""Canonical inbound/outbound header name for request-id propagation.

Lowercased per the HTTP/2 spec normalization that Starlette and FastAPI
apply when parsing request headers; outbound responses are written with
the same lowercase form for symmetry.
"""


@dataclass(frozen=True, slots=True)
class RequestIdContext:
    """Immutable record of how a request id was determined.

    ``inbound = True`` means the value came from the request header
    unchanged. ``inbound = False`` means the middleware generated a new
    id (the caller did not send one). The middleware NEVER overrides an
    inbound id; that is the lossless guarantee the wiring round can rely
    on when threading the id through structured logs.
    """

    request_id: str
    inbound: bool

    def to_dict(self) -> dict[str, Any]:
        return {"request_id": self.request_id, "inbound": self.inbound}


def _generate_request_id() -> str:
    """Return a fresh request id of shape ``req_<uuid4hex>``.

    The ``req_`` prefix mirrors the convention used elsewhere in the
    codebase for ticket-style identifiers and lets log scrapers tell at
    a glance whether the id was generated by owlmlx vs supplied by an
    upstream caller. UUID-4 hex (32 chars) is collision-resistant
    without coordinating state.
    """

    return f"req_{uuid.uuid4().hex}"


def derive_request_id_context(inbound_header_value: str | None) -> RequestIdContext:
    """Pure helper: derive the ``RequestIdContext`` for a header value.

    Extracted from ``RequestIdMiddleware`` so unit tests do not need a
    Starlette ``Request`` instance to verify the inbound/outbound rules.

    - non-empty trimmed inbound value -> ``inbound = True`` and the
      value is preserved verbatim
    - missing or empty value -> a fresh ``req_<uuid4hex>`` id is
      generated and ``inbound = False``
    """

    if inbound_header_value is None:
        return RequestIdContext(request_id=_generate_request_id(), inbound=False)
    trimmed = inbound_header_value.strip()
    if not trimmed:
        return RequestIdContext(request_id=_generate_request_id(), inbound=False)
    return RequestIdContext(request_id=trimmed, inbound=True)


class RequestIdMiddleware(BaseHTTPMiddleware):
    """Inbound/outbound ``x-request-id`` propagation.

    Inbound: read ``x-request-id`` from request headers; if absent or
    empty, generate ``req_<uuid4hex>`` via :func:`_generate_request_id`.
    Attach the resulting :class:`RequestIdContext` to
    ``request.state.request_id_context`` and the bare id to
    ``request.state.request_id`` (the bare id is the field handlers and
    structured loggers want most of the time; the context object is
    available for callers that need to know whether the id was
    inbound).

    Outbound: ensure the response carries ``x-request-id``. If the
    downstream handler already wrote one, do not overwrite it; only set
    when missing.

    Lossless contract: an inbound id is NEVER replaced. The wiring round
    can therefore rely on this middleware as the single point of truth
    for the request-id field in structured logs, error envelopes, and
    metrics labels.
    """

    async def dispatch(
        self,
        request: Request,
        call_next: Callable[[Request], Awaitable[Response]],
    ) -> Response:
        inbound_value = request.headers.get(REQUEST_ID_HEADER)
        context = derive_request_id_context(inbound_value)
        request.state.request_id_context = context
        request.state.request_id = context.request_id
        response = await call_next(request)
        # Lossless: never overwrite a header the handler already set.
        if REQUEST_ID_HEADER not in response.headers:
            response.headers[REQUEST_ID_HEADER] = context.request_id
        return response


