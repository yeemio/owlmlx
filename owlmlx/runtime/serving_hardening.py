# 2. Per-request timeout + client-disconnect detection
# ---------------------------------------------------------------------------


class RequestDisconnectedError(Exception):
    """Raised when ``poll_disconnect`` observes the client has gone away.

    The wiring round catches this in handler scope and converts it to
    the unified error envelope (see :class:`ErrorEnvelopeBuilder`) with
    ``error_code = "client_disconnected"`` and HTTP 499-equivalent. This
    scaffold does NOT decide the HTTP code; the wiring round decides
    that policy.
    """


@dataclass(frozen=True, slots=True)
class RequestTimeoutPolicy:
    """Per-request timeout policy.

    - ``default_timeout_s``: ceiling for non-streaming generation
      requests. Sized larger than typical decode latency; the wiring
      round may override per-route at install time.
    - ``streaming_timeout_s``: ceiling for streaming generation
      requests, sized larger because streaming responses can legitimately
      run for minutes on large weights.
    - ``disconnect_check_interval_s``: cadence for
      ``RequestTimeoutHelper.poll_disconnect`` to await
      ``Request.is_disconnected()``. Too short and the polling cost
      shows up in CPU profiles; too long and disconnect detection lags.
    """

    default_timeout_s: float = 60.0
    streaming_timeout_s: float = 600.0
    disconnect_check_interval_s: float = 0.5


class RequestTimeoutHelper:
    """Async helpers for timeout-bounded handlers and disconnect polling.

    This is async-native at the timeout boundary: ``await_with_timeout``
    is implemented via :func:`asyncio.wait_for`, NOT via threading or
    process spawn. The scaffold deliberately does not block on a thread
    waiting for the awaitable, because the FastAPI app is async and
    blocking the event loop for a timeout is the wrong shape.
    """

    def __init__(self, *, policy: RequestTimeoutPolicy | None = None) -> None:
        self._policy = policy or RequestTimeoutPolicy()

    @property
    def policy(self) -> RequestTimeoutPolicy:
        return self._policy

    async def await_with_timeout(
        self,
        awaitable: Awaitable[Any],
        *,
        timeout_s: float | None = None,
    ) -> Any:
        """Await ``awaitable`` with a per-call timeout.

        ``timeout_s`` overrides the policy's ``default_timeout_s`` when
        supplied. When ``timeout_s`` resolves to ``None`` (e.g. the
        wiring round disables the ceiling for a specific route), the
        awaitable runs unbounded — i.e. the helper degrades to a
        no-timeout wrapper rather than refusing the call.
        """

        effective_timeout = timeout_s if timeout_s is not None else self._policy.default_timeout_s
        if effective_timeout is None:
            return await awaitable
        return await asyncio.wait_for(awaitable, timeout=effective_timeout)

    async def poll_disconnect(
        self,
        request: Request,
        *,
        interval_s: float | None = None,
    ) -> AsyncIterator[None]:
        """Async generator that yields periodically until the client disconnects.

        Usage shape (deferred to the wiring round):

        .. code-block:: python

            async def handler(request: Request) -> Response:
                helper = RequestTimeoutHelper()
                gen_task = asyncio.create_task(_run_generation(request))
                async for _ in helper.poll_disconnect(request):
                    if gen_task.done():
                        break
                    # client still there

        Raises :class:`RequestDisconnectedError` once
        ``await request.is_disconnected()`` returns ``True``. The
        wiring round is responsible for cancelling the generation task
        upon catching this exception; the scaffold does not couple to
        any specific cancellation strategy.
        """

        cadence = (
            interval_s
            if interval_s is not None
            else self._policy.disconnect_check_interval_s
        )
        while True:
            disconnected = await request.is_disconnected()
            if disconnected:
                raise RequestDisconnectedError(
                    "client closed the connection before the response completed"
                )
            yield None
            await asyncio.sleep(cadence)


