@dataclass(frozen=True, slots=True)
class IdempotentLoadOutcome:
    """Outcome of an idempotent ``/v1/load`` interpretation step.

    ``already_loaded = True`` means the call's effect was a no-op
    because the model was resident before the call arrived. The wiring
    round translates this to HTTP 200 with a ``detail`` body, NOT to
    HTTP 409.

    ``ok`` is preserved as a separate field rather than collapsed into
    ``already_loaded`` because the typed runtime contract elsewhere
    in owlmlx exposes both. A genuine load failure resolves to
    ``ok = False, already_loaded = False``.
    """

    model_id: str
    already_loaded: bool
    memory_gb: float
    ok: bool = True

    def to_response_body(self) -> dict[str, Any]:
        return {
            "model_id": self.model_id,
            "already_loaded": self.already_loaded,
            "memory_gb": self.memory_gb,
            "ok": self.ok,
        }


class IdempotentLoadHelper:
    """Interpret a backend ``LoadResult``-shaped dict idempotently.

    The native and subprocess backends already return a ``LoadResult``
    dataclass with fields ``ok``, ``error_code``, ``model_id``,
    ``memory_gb``, ``detail``. Today the runtime returns HTTP 409 (or
    similar) when ``error_code == "model_already_loaded"`` even though
    the *caller's intent* — "the model should be resident" — is
    satisfied. This helper rewrites that one specific case into a
    success-with-detail envelope.

    All other failures (``backend_error``, ``invalid_request``, etc.)
    pass through unchanged via ``ok = False``. The wiring round
    converts those into the standard error envelope.
    """

    def interpret_backend_result(
        self,
        *,
        backend_result_dict: dict[str, Any],
    ) -> IdempotentLoadOutcome:
        ok = bool(backend_result_dict.get("ok", False))
        error_code = backend_result_dict.get("error_code")
        model_id = str(backend_result_dict.get("model_id", ""))
        memory_gb = float(backend_result_dict.get("memory_gb", 0.0) or 0.0)
        if not ok and error_code == "model_already_loaded":
            return IdempotentLoadOutcome(
                model_id=model_id,
                already_loaded=True,
                memory_gb=memory_gb,
                ok=True,
            )
        return IdempotentLoadOutcome(
            model_id=model_id,
            already_loaded=False,
            memory_gb=memory_gb,
            ok=ok,
        )


