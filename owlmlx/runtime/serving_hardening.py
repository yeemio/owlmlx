"""owlmlx serving hardening scaffold.

Defines the middleware, async helpers, and response shapes for six
serving-surface hardenings that improve credibility independent of any
batching or scheduler change:

1. Request-id propagation middleware
2. Per-request timeout + client-disconnect detection
3. Graceful shutdown that drains the GenerationGate
4. Unified structured error envelope
5. Prometheus-format metrics snapshot exporter (stdlib only)
6. Idempotent ``/v1/load`` outcome envelope

Scaffold-grade. ``runtime/server.py`` is NOT modified in this round to
install any of these. Wiring is a follow-up round whose responsibility
is to apply ``app.add_middleware(RequestIdMiddleware)``, attach the
graceful shutdown to ``app.router.on_shutdown``, etc., one item at a
time with operator review per hardening.

Ownership boundary:

- this module owns *primitives*: middleware classes, async helpers,
  immutable result/policy dataclasses, and a stdlib-only Prometheus text
  renderer
- ``runtime/server.py`` (lines 1-2343) remains read-only in this round;
  no FastAPI app is constructed here, no route is registered here, no
  ``app.add_middleware`` / ``app.add_exception_handler`` /
  ``app.router.on_shutdown`` call is made here
- ``owlmlx/serving.py`` ``GenerationGate`` (lines 104-979) is NOT
  imported here. The graceful shutdown receives a *callable* returning
  the same dict shape ``GenerationGate.status`` exposes, so the operator
  decides at wiring time which gate the drain observes
- ``owlmlx/runtime/mlx_native_backend.py`` ``_TicketedAdmission``
  ``snapshot()`` is also referenced only via dict shape; no import

Per ``docs/source-of-truth/native-mlx-backend-capability-matrix.md`` §7
the seven-line architectural assessment records **Line 4 — Serving
surface (`partial`)** as the lane this scaffold begins to close. The
matrix itself is about MLX backend capability entry points, not HTTP
serving primitives, so this scaffold does NOT promote any matrix row.
Serving-surface ownership is governed by
``docs/source-of-truth/single-host-orchestration-architecture.md`` and
the architecture doc that ships alongside this scaffold.

No new dependencies. The Prometheus text-exposition format is rendered
manually with ``io.StringIO`` so that neither ``prometheus_client`` nor
``psutil`` is added. Starlette pieces are imported because FastAPI
already depends on Starlette (FastAPI re-exports it); we use the
``starlette`` import path directly to make the boundary explicit.
"""

from __future__ import annotations

import asyncio
import io
import json
import time
import uuid
