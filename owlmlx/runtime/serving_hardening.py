# 3. Graceful shutdown that drains the GenerationGate
# ---------------------------------------------------------------------------


@dataclass(frozen=True, slots=True)
class GracefulShutdownConfig:
    """Configuration for the shutdown drain.

    - ``gate_idle_timeout_s``: maximum total time the drain waits for
      the gate to become idle before giving up and reporting timeout.
      Sized to a single-generation ceiling; the wiring round may raise
      it for fleets that deliberately allow long completions to
      finish.
    - ``unload_models_on_shutdown``: when ``True``, after the drain
      completes (whether by idle observation or timeout) the wiring
      round invokes the optional unload callable to release in-process
      model handles and trigger ``mx.clear_cache`` if the runtime
      extra is present.
    - ``poll_interval_s``: cadence at which ``drain_gate`` re-reads
      the gate status. Short enough that a freshly-idle gate is
      observed quickly; long enough that the polling loop is not a
      hot loop.
    """

    gate_idle_timeout_s: float = 30.0
    unload_models_on_shutdown: bool = True
    poll_interval_s: float = 0.05


class GracefulShutdown:
    """Drain the gate, then optionally unload models.

    Receives the gate's status surface as a *callable*, not as a direct
    reference to ``GenerationGate``. This keeps the scaffold decoupled
    from ``owlmlx/serving.py``: the operator passes
    ``lambda: gate.status`` (or any equivalent) at wiring time. The
    scaffold only assumes the dict has an ``is_active`` field that mirrors
    ``GenerationGate.is_active``'s boolean shape, plus opaque other
    fields it forwards verbatim into the shutdown report.

    The drain is observation-only. It does NOT call any gate method,
    does NOT cancel any in-flight generation, does NOT mutate gate
    state. If the operator needs forced cancellation, that is a separate
    primitive whose wiring is also deferred.
    """

    def __init__(self, *, config: GracefulShutdownConfig | None = None) -> None:
        self._config = config or GracefulShutdownConfig()

    @property
    def config(self) -> GracefulShutdownConfig:
        return self._config

    async def drain_gate(
        self,
        *,
        gate_status_callable: Callable[[], dict[str, Any]],
    ) -> dict[str, Any]:
        """Poll ``gate_status_callable()`` until idle or timeout.

        Returns a dict::

            {
                "drained": bool,            # True iff observed idle in time
                "elapsed_s": float,         # wall time spent draining
                "polls": int,               # number of status reads
                "final_status": dict,       # last observed status payload
                "timeout_s": float,         # config ceiling, for audit
            }

        The status payload shape is unchanged from what the callable
        returns; the scaffold only reads ``is_active`` from it. ``polls``
        is reported so the wiring round's structured shutdown log can
        distinguish "drained on first poll" (clean idle) from
        "drained after a long tail" (legitimate long-running
        generation).
        """

        deadline = time.monotonic() + self._config.gate_idle_timeout_s
        started_at = time.monotonic()
        polls = 0
        last_status: dict[str, Any] = {}
        drained = False
        while True:
            polls += 1
            last_status = gate_status_callable()
            if not last_status.get("is_active", False):
                drained = True
                break
            if time.monotonic() >= deadline:
                drained = False
                break
            await asyncio.sleep(self._config.poll_interval_s)
        elapsed = time.monotonic() - started_at
        return {
            "drained": drained,
            "elapsed_s": round(elapsed, 4),
            "polls": polls,
            "final_status": last_status,
            "timeout_s": self._config.gate_idle_timeout_s,
        }

    async def on_shutdown(
        self,
        *,
        gate_status_callable: Callable[[], dict[str, Any]],
        unload_models_callable: Callable[[], Awaitable[dict[str, Any]] | dict[str, Any]]
        | None = None,
    ) -> dict[str, Any]:
        """Orchestrate drain then optional unload.

        ``unload_models_callable`` may be sync or async; both shapes
        are accepted because owlmlx's existing unload paths are
        synchronous (``MlxNativeBackend.unload`` returns a dataclass)
        but a future round may want async unload to overlap with cache
        clear. The scaffold accepts both; if the callable returns a
        dict directly it is treated as the unload report.

        The returned report is a dict suitable for embedding in the
        runtime's structured shutdown log. It is NOT a Pydantic model
        because lifespan handlers do not return Pydantic anyway.
        """

        drain_report = await self.drain_gate(gate_status_callable=gate_status_callable)
        unload_report: dict[str, Any] | None = None
        if self._config.unload_models_on_shutdown and unload_models_callable is not None:
            outcome = unload_models_callable()
            if asyncio.iscoroutine(outcome) or hasattr(outcome, "__await__"):
                unload_report = await outcome  # type: ignore[assignment]
            else:
                unload_report = outcome  # type: ignore[assignment]
        return {
            "drain": drain_report,
            "unload": unload_report,
            "config": {
                "gate_idle_timeout_s": self._config.gate_idle_timeout_s,
                "unload_models_on_shutdown": self._config.unload_models_on_shutdown,
                "poll_interval_s": self._config.poll_interval_s,
            },
        }


