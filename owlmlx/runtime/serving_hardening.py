# 5. Prometheus-format metrics snapshot exporter (stdlib only)
# ---------------------------------------------------------------------------


@dataclass(frozen=True, slots=True)
class _PromMetric:
    """Internal helper for one Prometheus line group.

    Carries the metric name, kind (``counter`` vs ``gauge``), help
    text, and the numeric value. Used only inside
    :class:`MetricsSnapshotExporter`; not part of the public surface.
    """

    name: str
    kind: str
    help_text: str
    value: float


def _format_prom_value(value: Any) -> str:
    """Render a Python numeric/bool into Prometheus-text-format value.

    Booleans become ``1`` / ``0``. Floats and ints render via ``repr``
    with normalization so that the rendered text is stable across
    platforms (no platform-dependent float exponent shifting).
    """

    if isinstance(value, bool):
        return "1" if value else "0"
    if isinstance(value, int):
        return str(value)
    if isinstance(value, float):
        if value != value:  # NaN
            return "NaN"
        if value == float("inf"):
            return "+Inf"
        if value == float("-inf"):
            return "-Inf"
        # Avoid scientific notation flapping the diff for small floats.
        text = repr(value)
        return text
    return str(value)


class MetricsSnapshotExporter:
    """Render a Prometheus text-exposition snapshot from owlmlx state.

    Reads two read-only inputs:

    - ``gate_status``: a dict shaped like ``GenerationGate.status``
      (waiters, total_served, total_queued, longest_wait_s,
      longest_exec_s, generation_gate)
    - ``native_admission_snapshot``: optional dict shaped like
      ``MlxNativeBackend.status().detail.admission`` (next_ticket,
      serving, in_critical_section, max_observed_concurrency)

    The exporter does NOT pull these from any module; the wiring round
    is responsible for plumbing them in at the ``/metrics`` route.
    Counter metrics carry ``_total`` suffix per Prometheus convention;
    gauges do not.

    Stdlib-only: rendering uses ``io.StringIO``. ``prometheus_client``
    is intentionally not a dependency.
    """

    def __init__(self, *, namespace: str = "owlmlx_native") -> None:
        self._namespace = namespace

    def _name(self, suffix: str) -> str:
        return f"{self._namespace}_{suffix}"

    def render_prometheus_text(
        self,
        *,
        gate_status: dict[str, Any],
        native_admission_snapshot: dict[str, Any] | None,
    ) -> str:
        """Render the Prometheus text-exposition format snapshot.

        Output shape (one ``# HELP`` and ``# TYPE`` line per metric,
        followed by the value line). Metrics omitted when the source
        dict is missing the field — the exporter does NOT fabricate
        zeros for missing inputs because that would smear the
        boundary between "no data" and "actually zero".
        """

        metrics: list[_PromMetric] = []

        # Gauge: current waiter count
        if "waiters" in gate_status:
            metrics.append(
                _PromMetric(
                    name=self._name("waiters"),
                    kind="gauge",
                    help_text="Number of waiters currently blocked on the GenerationGate.",
                    value=gate_status["waiters"],
                )
            )

        # Counter: total requests served by the gate (cumulative)
        if "total_served" in gate_status:
            metrics.append(
                _PromMetric(
                    name=self._name("total_served_total"),
                    kind="counter",
                    help_text="Cumulative count of generations the gate has admitted to completion.",
                    value=gate_status["total_served"],
                )
            )

        # Counter: total requests queued by the gate
        if "total_queued" in gate_status:
            metrics.append(
                _PromMetric(
                    name=self._name("total_queued_total"),
                    kind="counter",
                    help_text="Cumulative count of generations that had to queue (were not immediately admitted).",
                    value=gate_status["total_queued"],
                )
            )

        # Gauge: longest wait observed (seconds)
        if "longest_wait_s" in gate_status:
            metrics.append(
                _PromMetric(
                    name=self._name("longest_wait_seconds"),
                    kind="gauge",
                    help_text="Longest wait time (seconds) observed since process start.",
                    value=gate_status["longest_wait_s"],
                )
            )

        # Gauge: longest exec observed (seconds)
        if "longest_exec_s" in gate_status:
            metrics.append(
                _PromMetric(
                    name=self._name("longest_exec_seconds"),
                    kind="gauge",
                    help_text="Longest in-gate execution time (seconds) observed since process start.",
                    value=gate_status["longest_exec_s"],
                )
            )

        if native_admission_snapshot is not None:
            if "max_observed_concurrency" in native_admission_snapshot:
                metrics.append(
                    _PromMetric(
                        name=self._name("native_max_observed_concurrency"),
                        kind="gauge",
                        help_text=(
                            "High-water mark of concurrent in-critical-section "
                            "admissions on the native MLX backend."
                        ),
                        value=native_admission_snapshot["max_observed_concurrency"],
                    )
                )
            if "in_critical_section" in native_admission_snapshot:
                metrics.append(
                    _PromMetric(
                        name=self._name("native_in_critical_section"),
                        kind="gauge",
                        help_text=(
                            "Number of admissions currently inside the native "
                            "MLX backend critical section."
                        ),
                        value=native_admission_snapshot["in_critical_section"],
                    )
                )
            if "serving" in native_admission_snapshot:
                metrics.append(
                    _PromMetric(
                        name=self._name("native_serving_ticket"),
                        kind="gauge",
                        help_text=(
                            "Monotonic ticket value the native MLX admission "
                            "is currently serving."
                        ),
                        value=native_admission_snapshot["serving"],
                    )
                )

        buf = io.StringIO()
        for metric in metrics:
            buf.write(f"# HELP {metric.name} {metric.help_text}\n")
            buf.write(f"# TYPE {metric.name} {metric.kind}\n")
            buf.write(f"{metric.name} {_format_prom_value(metric.value)}\n")
        return buf.getvalue()


