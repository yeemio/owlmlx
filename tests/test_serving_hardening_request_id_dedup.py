def test_no_inbound_id_uses_middleware_generated_id_in_compat_response() -> None:
    """No inbound header: response body's ``id`` matches the response's x-request-id header.

    Proves the middleware-generated id is the single source for both
    the outbound header AND the compat body's ``id`` field. Before
    D-5, these would have been two independently generated values.
    """

    app = _build_real_owlmlx_app()
    with TestClient(app) as client:
        response = client.post(
            "/v1/chat/completions",
            json={
                "model": "no-such-model-d5-autogen",
                "messages": [{"role": "user", "content": "hello"}],
            },
        )
    assert response.status_code in (404, 503), response.text
    assert REQUEST_ID_HEADER in response.headers
    header_id = response.headers[REQUEST_ID_HEADER]
    # Per RequestIdMiddleware contract: req_<uuid4hex> (32 hex chars).
    assert header_id.startswith("req_")
    assert len(header_id) == len("req_") + 32
    body = response.json()
    # Body ``id`` is the same middleware-set value as the header.
    assert body["id"] == header_id


