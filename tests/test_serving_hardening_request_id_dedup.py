"""Integration tests for D-5 per-route request_id dedup on the real owlmlx app.

These tests construct the actual owlmlx FastAPI app via
``owlmlx.runtime.server.create_app(...)`` and exercise the compat
routes (``/v1/chat/completions``, ``/v1/messages``, ``/v1/completions``)
end-to-end with ``fastapi.testclient.TestClient``. No uvicorn process
is spawned and no model is loaded.

Background: prior to D-5, each compat route generated its own
``req_<uuid4hex>`` locally — in parallel to the D-1
``RequestIdMiddleware`` that already sets ``request.state.request_id``
(honoring inbound ``x-request-id`` if present). D-5 removes that
per-route generation so the middleware-set id is the single source.

These tests pin the new contract:

- Inbound ``x-request-id`` propagates verbatim into compat response
  body's ``id`` field (chat completions, messages, completions).
- When no inbound id is provided, the autogenerated middleware id
  matches the response body's ``id`` (single source proof).
- Compat error envelope's ``request_id``/``id`` field carries the
  inbound ``x-request-id`` (no longer a freshly generated value).

The companion file ``tests/test_serving_hardening_wired.py`` exercises
the middleware on ``/healthz`` and 404 paths; this file is the compat
route counterpart.
"""

from __future__ import annotations

from fastapi.testclient import TestClient

from owlmlx.runtime.server import create_app
from owlmlx.runtime.serving_hardening import REQUEST_ID_HEADER


def _build_real_owlmlx_app():
    """Build the real owlmlx FastAPI app with no optional ledgers wired."""

    return create_app()


def test_inbound_request_id_propagates_to_chat_completions_response_id() -> None:
    """Inbound x-request-id is the value that lands in compat error body's ``id``.

    POST /v1/chat/completions against an unloaded model triggers the
    ``model_not_loaded`` error path which routes through
    ``_compat_error_response`` — that builder uses ``request_id`` for
    both the ``x-request-id`` header and the body's ``id`` field. After
    D-5, the ``request_id`` value comes from
    ``request.state.request_id`` (i.e. the middleware) rather than a
    fresh local uuid, so an inbound header MUST round-trip verbatim.
    """

    app = _build_real_owlmlx_app()
    inbound_id = "req_test-inbound-123"
    with TestClient(app) as client:
        response = client.post(
            "/v1/chat/completions",
            headers={REQUEST_ID_HEADER: inbound_id},
            json={
                "model": "no-such-model-d5",
                "messages": [{"role": "user", "content": "hello"}],
            },
        )
    assert response.status_code in (404, 503), response.text
    assert response.headers[REQUEST_ID_HEADER] == inbound_id
    body = response.json()
    assert body["id"] == inbound_id
    assert body["object"] == "error"


